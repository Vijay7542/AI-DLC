"""Workflow state schema for Mini AI-DLC."""

from typing import Optional, List, Dict, Literal, TypedDict
from datetime import datetime
from pydantic import BaseModel, Field


class Task(BaseModel):
    """A task in the implementation plan."""

    id: str = Field(description="Unique task identifier")
    description: str = Field(description="Task description")
    status: Literal["pending", "in_progress", "completed", "failed"] = Field(
        default="pending", description="Task status"
    )
    dependencies: List[str] = Field(
        default_factory=list, description="List of task IDs this task depends on"
    )


class Subtask(BaseModel):
    """A detailed subtask for implementation."""

    id: str = Field(description="Unique subtask identifier")
    parent_task_id: str = Field(description="ID of the parent task")
    description: str = Field(description="Detailed subtask description")
    priority: Literal["low", "medium", "high", "critical"] = Field(
        default="medium", description="Task priority"
    )
    complexity: Literal["simple", "moderate", "complex", "very_complex"] = Field(
        default="moderate", description="Task complexity level"
    )
    estimated_hours: Optional[float] = Field(
        default=None, description="Estimated effort in hours"
    )
    dependencies: List[str] = Field(
        default_factory=list, description="List of subtask IDs this depends on"
    )
    parallel_group: Optional[str] = Field(
        default=None, description="Group ID for parallel execution"
    )
    blockers: List[str] = Field(
        default_factory=list, description="List of blockers or dependencies"
    )
    status: Literal["pending", "in_progress", "completed", "failed", "blocked"] = Field(
        default="pending", description="Subtask status"
    )


class ExecutionPlan(BaseModel):
    """Structured execution plan for the project."""

    subtasks: List[Subtask] = Field(
        default_factory=list, description="List of detailed subtasks"
    )
    execution_order: List[str] = Field(
        default_factory=list, description="Ordered list of subtask IDs for execution"
    )
    parallel_groups: Dict[str, List[str]] = Field(
        default_factory=dict, description="Groups of subtasks that can run in parallel"
    )
    critical_path: List[str] = Field(
        default_factory=list, description="Subtasks on the critical path"
    )
    total_estimated_hours: Optional[float] = Field(
        default=None, description="Total estimated effort"
    )
    technical_dependencies: List[str] = Field(
        default_factory=list, description="Technical dependencies to resolve"
    )


class FileVersion(BaseModel):
    """Version information for a generated file."""

    version: int = Field(description="Version number")
    content: str = Field(description="File content at this version")
    generated_by: str = Field(description="Subtask ID that generated this version")
    timestamp: datetime = Field(description="When this version was created")
    description: str = Field(description="Description of changes in this version")
    syntax_valid: bool = Field(default=True, description="Whether syntax is valid")


class GeneratedFile(BaseModel):
    """Information about a generated file."""

    file_path: str = Field(description="Relative path to the file")
    current_version: int = Field(default=1, description="Current version number")
    versions: List[FileVersion] = Field(
        default_factory=list, description="Version history"
    )
    generated_by: str = Field(description="Subtask ID that created this file")
    created_at: datetime = Field(description="When the file was first created")
    last_modified: datetime = Field(description="When the file was last modified")
    syntax_valid: bool = Field(default=True, description="Current syntax validity")


class TaskExecutionRecord(BaseModel):
    """Record of task execution for tracking."""

    subtask_id: str = Field(description="Subtask ID")
    description: str = Field(description="Subtask description")
    status: Literal["pending", "in_progress", "completed", "failed", "blocked"] = Field(
        default="pending", description="Execution status"
    )
    generated_files: List[str] = Field(
        default_factory=list, description="Files generated by this task"
    )
    started_at: Optional[datetime] = Field(default=None, description="When task started")
    completed_at: Optional[datetime] = Field(default=None, description="When task completed")
    errors: List[str] = Field(default_factory=list, description="Errors encountered")
    retry_count: int = Field(default=0, description="Number of retries")
    syntax_validation_passed: bool = Field(default=True, description="Whether generated code passed syntax validation")


class TestCase(BaseModel):
    """A test case for the generated application."""

    test_id: str = Field(description="Unique test identifier")
    test_name: str = Field(description="Human-readable test name")
    test_type: Literal["unit", "integration", "system"] = Field(
        default="unit", description="Type of test"
    )
    file_path: str = Field(description="Path to test file")
    function_name: str = Field(description="Function being tested")
    description: str = Field(description="Test description")
    status: Literal["pending", "passed", "failed", "skipped", "error"] = Field(
        default="pending", description="Test execution status"
    )
    error_message: Optional[str] = Field(default=None, description="Error message if failed")
    execution_time: Optional[float] = Field(default=None, description="Execution time in seconds")


class BugReport(BaseModel):
    """A bug report from test failures."""

    bug_id: str = Field(description="Unique bug identifier")
    test_id: str = Field(description="Test ID that revealed the bug")
    failure_type: Literal["syntax_error", "runtime_error", "dependency_error", "logical_error", "assertion_error"] = Field(
        description="Type of failure"
    )
    file_path: str = Field(description="File where bug occurred")
    line_number: Optional[int] = Field(default=None, description="Line number of error")
    error_message: str = Field(description="Error message")
    stack_trace: Optional[str] = Field(default=None, description="Stack trace if available")
    severity: Literal["low", "medium", "high", "critical"] = Field(
        default="medium", description="Bug severity"
    )
    suggested_fix: Optional[str] = Field(default=None, description="Suggested fix from LLM")
    status: Literal["open", "in_progress", "fixed", "cannot_reproduce"] = Field(
        default="open", description="Bug status"
    )


class TestReport(BaseModel):
    """Structured test execution report."""

    total_tests: int = Field(default=0, description="Total number of tests")
    passed_tests: int = Field(default=0, description="Number of passed tests")
    failed_tests: int = Field(default=0, description="Number of failed tests")
    skipped_tests: int = Field(default=0, description="Number of skipped tests")
    test_cases: List[TestCase] = Field(
        default_factory=list, description="All test cases"
    )
    bug_reports: List[BugReport] = Field(
        default_factory=list, description="Bug reports from failures"
    )
    execution_time: Optional[float] = Field(default=None, description="Total execution time")
    test_coverage: Optional[float] = Field(default=None, description="Code coverage percentage")
    generated_at: datetime = Field(default_factory=datetime.now, description="When report was generated")


class DeploymentConfig(BaseModel):
    """Deployment configuration for the application."""

    environment: Literal["development", "staging", "production"] = Field(
        default="development", description="Deployment environment"
    )
    docker_image_name: str = Field(description="Docker image name")
    docker_image_tag: str = Field(description="Docker image tag")
    port: int = Field(default=8000, description="Application port")
    environment_variables: Dict[str, str] = Field(
        default_factory=dict, description="Environment variables (no secrets)"
    )
    resource_limits: Optional[Dict[str, str]] = Field(
        default=None, description="CPU/memory limits"
    )
    health_check_path: str = Field(default="/health", description="Health check endpoint")
    created_at: datetime = Field(default_factory=datetime.now, description="When config was created")


class BuildReport(BaseModel):
    """Report from build process."""

    build_id: str = Field(description="Unique build identifier")
    status: Literal["pending", "building", "success", "failed"] = Field(
        default="pending", description="Build status"
    )
    started_at: Optional[datetime] = Field(default=None, description="When build started")
    completed_at: Optional[datetime] = Field(default=None, description="When build completed")
    build_time: Optional[float] = Field(default=None, description="Build time in seconds")
    docker_image_id: Optional[str] = Field(default=None, description="Docker image ID")
    build_logs: List[str] = Field(default_factory=list, description="Build logs")
    errors: List[str] = Field(default_factory=list, description="Build errors")


class DeploymentReport(BaseModel):
    """Report from deployment process."""

    deployment_id: str = Field(description="Unique deployment identifier")
    build_id: str = Field(description="Build ID being deployed")
    environment: Literal["development", "staging", "production"] = Field(
        description="Deployment environment"
    )
    status: Literal["pending", "deploying", "success", "failed", "rolled_back"] = Field(
        default="pending", description="Deployment status"
    )
    started_at: Optional[datetime] = Field(default=None, description="When deployment started")
    completed_at: Optional[datetime] = Field(default=None, description="When deployment completed")
    deployment_time: Optional[float] = Field(default=None, description="Deployment time in seconds")
    container_id: Optional[str] = Field(default=None, description="Docker container ID")
    deployment_logs: List[str] = Field(default_factory=list, description="Deployment logs")
    errors: List[str] = Field(default_factory=list, description="Deployment errors")


class HealthCheckResult(BaseModel):
    """Result of health check on deployed application."""

    check_id: str = Field(description="Unique health check identifier")
    deployment_id: str = Field(description="Deployment ID being checked")
    status: Literal["healthy", "unhealthy", "unknown"] = Field(
        default="unknown", description="Health status"
    )
    response_time: Optional[float] = Field(default=None, description="Response time in ms")
    status_code: Optional[int] = Field(default=None, description="HTTP status code")
    error_message: Optional[str] = Field(default=None, description="Error message if unhealthy")
    checked_at: datetime = Field(default_factory=datetime.now, description="When check was performed")


class RollbackReport(BaseModel):
    """Report from rollback process."""

    rollback_id: str = Field(description="Unique rollback identifier")
    deployment_id: str = Field(description="Deployment ID being rolled back")
    previous_deployment_id: str = Field(description="Deployment ID to rollback to")
    status: Literal["pending", "rolling_back", "success", "failed"] = Field(
        default="pending", description="Rollback status"
    )
    started_at: Optional[datetime] = Field(default=None, description="When rollback started")
    completed_at: Optional[datetime] = Field(default=None, description="When rollback completed")
    rollback_time: Optional[float] = Field(default=None, description="Rollback time in seconds")
    rollback_logs: List[str] = Field(default_factory=list, description="Rollback logs")
    errors: List[str] = Field(default_factory=list, description="Rollback errors")


class WorkflowState(TypedDict):
    """Shared workflow state that flows through the LangGraph workflow.

    Designed to be modular and extensible for future features:
    - Business requirement change detection
    - Impact analysis
    - Task replanning
    - Human approval workflows
    """

    # Workflow identification
    workflow_id: str
    thread_id: str  # LangGraph thread ID for checkpointing

    # User input
    user_requirements: str

    # Workflow control
    phase: Literal["inception", "planning", "construction", "testing", "operations", "completed"]
    current_step: str
    human_approval_needed: bool
    approval_status: Literal["pending", "approved", "rejected", "awaiting_approval"]
    human_feedback: Optional[str]

    # Inception outputs
    requirements_doc: Optional[str]
    acceptance_criteria: Optional[List[str]]
    architecture: Optional[str]
    tasks: Optional[List[Dict]]  # Use Dict for serialization compatibility

    # Construction outputs
    generated_code: Optional[Dict[str, str]]  # filename -> code
    test_results: Optional[Dict[str, bool]]  # test_name -> passed
    code_changes_pending: bool
    workspace_path: Optional[str]  # Path to generated project workspace
    task_execution_records: Optional[Dict[str, Dict]]  # subtask_id -> execution record
    generated_files: Optional[Dict[str, Dict]]  # file_path -> file metadata
    file_versions: Optional[Dict[str, List[Dict]]]  # file_path -> version history
    construction_status: Literal["not_started", "in_progress", "completed", "failed"]

    # Testing outputs
    test_report: Optional[Dict]  # Structured test report
    test_cases: Optional[Dict[str, Dict]]  # test_id -> test case
    bug_reports: Optional[Dict[str, Dict]]  # bug_id -> bug report
    testing_status: Literal["not_started", "in_progress", "completed", "failed", "sandbox_unavailable"]
    correction_retry_count: int  # Number of code correction attempts

    # Operations outputs
    deployment_docs: Optional[str]
    monitoring_plan: Optional[str]
    deployment_config: Optional[Dict]  # Deployment configuration
    build_report: Optional[Dict]  # Build process report
    deployment_report: Optional[Dict]  # Deployment report
    health_check_result: Optional[Dict]  # Health check result
    rollback_report: Optional[Dict]  # Rollback report
    operations_status: Literal["not_started", "in_progress", "completed", "failed", "docker_unavailable"]
    deployment_approval_needed: bool  # Whether deployment needs human approval
    deployment_approval_status: Literal["pending", "approved", "rejected"]

    # Error handling
    errors: List[str]
    retry_count: int

    # Extensibility fields for future features
    # Requirement change tracking
    requirement_changes: Optional[List[Dict[str, str]]]  # Change history
    impact_analysis: Optional[Dict[str, str]]  # Impact assessment results

    # Task replanning
    replanned_tasks: Optional[List[Task]]  # Updated task list after replanning
    replanning_reason: Optional[str]  # Why replanning was triggered

    # Planning outputs
    execution_plan: Optional[Dict]  # Structured execution plan

    # Additional metadata
    metadata: Optional[Dict[str, str]]  # Flexible metadata for future extensions
