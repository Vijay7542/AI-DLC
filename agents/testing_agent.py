"""Testing Agent for Mini AI-DLC.

Validates applications generated by Construction Agent.
Generates and executes tests in controlled environment.
Classifies failures and generates bug reports.
"""

import os
import json
import uuid
import subprocess
import logging
from typing import Any, List, Dict, Optional
from datetime import datetime
from graph.state import (
    WorkflowState,
    TestCase,
    BugReport,
    TestReport,
)
from agents.base_agent import BaseAgent
from agents.docker_utils import convert_path_for_docker, check_docker_ready
from agents.construction_agent import ConstructionAgent
from agents.version_manager import VersionManager
from langchain_core.messages import BaseMessage

logger = logging.getLogger(__name__)


class TestingAgent(BaseAgent):
    """Agent for the Testing phase of AI-DLC.

    Generates tests from requirements and executes them.
    Features:
    - Test generation from acceptance criteria
    - Test execution in isolated environment
    - Failure classification
    - Bug report generation
    - Code correction loop with retry limit
    """

    def __init__(self, llm=None, use_test_config=False, max_corrections: int = 3, version_db: str = "version_history.db"):
        """Initialize the Testing Agent.

        Args:
            llm: Optional LLM instance for testing
            use_test_config: If True, use TestConfig
            max_corrections: Maximum number of code correction attempts
            version_db: Path to version history database
        """
        super().__init__(llm=llm, use_test_config=use_test_config)
        self.max_corrections = max_corrections
        self.version_manager = VersionManager(version_db)

    def process(self, state: WorkflowState) -> Dict[str, Any]:
        """Process the Testing phase.

        Args:
            state: Current workflow state with constructed application

        Returns:
            State updates with testing outputs
        """
        workspace_path = state.get("workspace_path")
        if not workspace_path:
            raise ValueError("Testing Agent requires constructed application")

        # Check if Docker is available for sandbox
        if not check_docker_ready():
            return {
                "testing_status": "sandbox_unavailable",
                "phase": "testing",
                "current_step": "testing_complete",
                "errors": ["Docker sandbox not available - cannot safely execute tests"],
            }

        # Generate tests
        test_cases = self._generate_tests(state)

        # Execute tests
        test_report = self._execute_tests(test_cases, workspace_path)

        # If tests failed, attempt correction loop
        correction_count = 0
        previous_test_report = test_report  # Track previous results for regression

        while test_report.failed_tests > 0 and correction_count < self.max_corrections:
            # Generate bug reports
            bug_reports = self._classify_failures(test_report)

            # Request code corrections
            correction_made = self._request_corrections(bug_reports, state)

            if not correction_made:
                break

            # Re-run tests (regression testing)
            new_test_report = self._execute_tests(test_cases, workspace_path, run_all=True)

            # Check for regression (new failures)
            regression_detected = self._detect_regression(previous_test_report, new_test_report)
            
            if regression_detected:
                # Regression detected - rollback all corrected files
                self._rollback_corrections(bug_reports, state, "Regression detected")
                break

            # If tests passed, mark versions as working
            if new_test_report.failed_tests == 0:
                self._mark_corrections_as_working(bug_reports, state)

            test_report = new_test_report
            correction_count += 1

        result = {
            "test_report": test_report.model_dump(),
            "test_cases": {tc.test_id: tc.model_dump() for tc in test_cases},
            "bug_reports": {br.bug_id: br.model_dump() for br in test_report.bug_reports},
            "testing_status": "completed" if test_report.failed_tests == 0 else "failed",
            "correction_retry_count": correction_count,
            "phase": "testing",
            "current_step": "testing_complete",
        }

        return result

    def _generate_tests(self, state: WorkflowState) -> List[TestCase]:
        """Generate test cases from requirements and acceptance criteria.

        Args:
            state: Current workflow state

        Returns:
            List of generated test cases
        """
        requirements_doc = state.get("requirements_doc", "")
        acceptance_criteria = state.get("acceptance_criteria", [])
        architecture = state.get("architecture", "")
        generated_files = state.get("generated_files", {})

        system_prompt = self.create_system_prompt(
            """You are an expert software tester.
            Generate comprehensive unit and integration tests based on requirements and acceptance criteria.
            
            For each test, provide:
            - Test name
            - Type (unit or integration)
            - File path for the test file
            - Function being tested
            - Test description
            
            Return as a JSON array of test objects."""
        )

        user_prompt = self.create_user_prompt(
            f"""Generate tests for the following application:

REQUIREMENTS:
{requirements_doc[:1000]}...

ACCEPTANCE CRITERIA:
{json.dumps(acceptance_criteria, indent=2)}

ARCHITECTURE:
{architecture[:1000]}...

GENERATED FILES:
{list(generated_files.keys())}

Generate unit tests for individual functions and integration tests for component interactions.
Return the result as a JSON array."""
        )

        response = self.invoke_llm([system_prompt, user_prompt])

        try:
            test_data = json.loads(response.content)
            test_cases = []
            for i, test_item in enumerate(test_data):
                test_case = TestCase(
                    test_id=f"test-{uuid.uuid4()}",
                    test_name=test_item.get("test_name", f"Test {i}"),
                    test_type=test_item.get("test_type", "unit"),
                    file_path=test_item.get("file_path", f"tests/test_{i}.py"),
                    function_name=test_item.get("function_name", ""),
                    description=test_item.get("description", ""),
                )
                test_cases.append(test_case)
            return test_cases
        except json.JSONDecodeError:
            # Fallback: create simple test cases
            return [
                TestCase(
                    test_id=f"test-{uuid.uuid4()}",
                    test_name="Basic Test",
                    test_type="unit",
                    file_path="tests/test_basic.py",
                    function_name="test_basic",
                    description="Basic functionality test",
                )
            ]

    def _parse_pytest_output(self, stdout: str, stderr: str) -> Dict[str, str]:
        """Parse pytest output to extract individual test results.

        Args:
            stdout: Standard output from pytest
            stderr: Standard error from pytest

        Returns:
            Dictionary mapping test names to their status (passed/failed/skipped)
        """
        results = {}
        lines = (stdout + "\n" + stderr).split("\n")
        
        current_test = None
        for line in lines:
            # Match pytest output lines like:
            # test_module.py::test_function PASSED
            # test_module.py::test_function FAILED
            # test_module.py::test_function SKIPPED
            if "::test_" in line and ("PASSED" in line or "FAILED" in line or "SKIPPED" in line):
                parts = line.split()
                if len(parts) >= 2:
                    test_name = parts[0]
                    status = parts[1].lower()
                    if status == "passed":
                        results[test_name] = "passed"
                    elif status == "failed":
                        results[test_name] = "failed"
                    elif status == "skipped":
                        results[test_name] = "skipped"
        
        return results

    def _execute_tests(self, test_cases: List[TestCase], workspace_path: str, run_all: bool = False) -> TestReport:
        """Execute tests in isolated environment.

        Args:
            test_cases: List of test cases to execute
            workspace_path: Path to workspace
            run_all: If True, run all tests in workspace (regression mode)

        Returns:
            Test execution report
        """
        passed = 0
        failed = 0
        skipped = 0
        executed_tests = []
        bug_reports = []

        if run_all:
            # Regression mode: run all tests in workspace using pytest discovery
            docker_workspace_path = convert_path_for_docker(workspace_path)
            
            result = subprocess.run(
                [
                    "docker", "run", "--rm",
                    "-v", f"{docker_workspace_path}:/app",
                    "-w", "/app",
                    "python:3.14-slim",
                    "python", "-m", "pytest", "-v", "--tb=short"
                ],
                capture_output=True,
                text=True,
                timeout=60,  # Longer timeout for full suite
            )
            
            # Parse pytest output to extract individual test results
            test_results = self._parse_pytest_output(result.stdout, result.stderr)
            
            for test_name, test_status in test_results.items():
                test_case = TestCase(
                    test_id=f"test-{len(executed_tests)}",
                    test_name=test_name,
                    test_type="regression",
                    file_path="all_tests",
                    function_name="unknown",
                    description=f"Regression test: {test_name}",
                    status=test_status,
                )
                
                if test_status == "passed":
                    passed += 1
                elif test_status == "failed":
                    failed += 1
                    test_case.error_message = "Test failed during regression"
                    # Create bug report for regression failures
                    bug_report = self._classify_failure(test_case, result.stderr)
                    bug_reports.append(bug_report)
                elif test_status == "skipped":
                    skipped += 1
                else:
                    failed += 1
                    test_case.error_message = "Test error during regression"
                
                executed_tests.append(test_case)
            
        else:
            # Normal mode: execute specific test cases
            for test_case in test_cases:
                try:
                    # Normalize test file path to use platform-appropriate separators
                    normalized_file_path = test_case.file_path.replace("/", os.sep)
                    test_file_path = os.path.join(workspace_path, normalized_file_path)
                    os.makedirs(os.path.dirname(test_file_path), exist_ok=True)

                    # Convert workspace path to Docker-compatible format
                    docker_workspace_path = convert_path_for_docker(workspace_path)

                    # Execute test using pytest in Docker
                    result = subprocess.run(
                        [
                            "docker", "run", "--rm",
                            "-v", f"{docker_workspace_path}:/app",
                            "-w", "/app",
                            "python:3.14-slim",
                            "python", "-m", "pytest", test_case.file_path, "-v"
                        ],
                        capture_output=True,
                        text=True,
                        timeout=30,
                    )

                    if result.returncode == 0:
                        test_case.status = "passed"
                        passed += 1
                    else:
                        test_case.status = "failed"
                        test_case.error_message = result.stderr[:500]
                        failed += 1

                        # Classify failure and create bug report
                        bug_report = self._classify_failure(test_case, result.stderr)
                        bug_reports.append(bug_report)

                except subprocess.TimeoutExpired:
                    test_case.status = "error"
                    test_case.error_message = "Test execution timeout"
                    failed += 1
                except Exception as e:
                    test_case.status = "error"
                    test_case.error_message = str(e)
                    failed += 1

                executed_tests.append(test_case)
            try:
                # Normalize test file path to use platform-appropriate separators
                normalized_file_path = test_case.file_path.replace("/", os.sep)
                test_file_path = os.path.join(workspace_path, normalized_file_path)
                os.makedirs(os.path.dirname(test_file_path), exist_ok=True)

                # Convert workspace path to Docker-compatible format
                docker_workspace_path = convert_path_for_docker(workspace_path)

                # Execute test using pytest in Docker
                result = subprocess.run(
                    [
                        "docker", "run", "--rm",
                        "-v", f"{docker_workspace_path}:/app",
                        "-w", "/app",
                        "python:3.14-slim",
                        "python", "-m", "pytest", test_case.file_path, "-v"
                    ],
                    capture_output=True,
                    text=True,
                    timeout=30,
                )

                if result.returncode == 0:
                    test_case.status = "passed"
                    passed += 1
                else:
                    test_case.status = "failed"
                    test_case.error_message = result.stderr[:500]
                    failed += 1

                    # Classify failure and create bug report
                    bug_report = self._classify_failure(test_case, result.stderr)
                    bug_reports.append(bug_report)

            except subprocess.TimeoutExpired:
                test_case.status = "error"
                test_case.error_message = "Test execution timeout"
                failed += 1
            except Exception as e:
                test_case.status = "error"
                test_case.error_message = str(e)
                failed += 1

            executed_tests.append(test_case)

        return TestReport(
            total_tests=len(executed_tests),
            passed_tests=passed,
            failed_tests=failed,
            skipped_tests=skipped,
            test_cases=executed_tests,
            bug_reports=bug_reports,
        )

    def _classify_failure(self, test_case: TestCase, error_output: str) -> BugReport:
        """Classify test failure and create bug report.

        Args:
            test_case: Failed test case
            error_output: Error output from test execution

        Returns:
            Bug report
        """
        # Simple classification based on error output
        if "SyntaxError" in error_output:
            failure_type = "syntax_error"
        elif "ImportError" in error_output or "ModuleNotFoundError" in error_output:
            failure_type = "dependency_error"
        elif "AssertionError" in error_output:
            failure_type = "assertion_error"
        elif "RuntimeError" in error_output:
            failure_type = "runtime_error"
        elif "Exception" in error_output:
            failure_type = "runtime_error"
        else:
            failure_type = "logical_error"

        return BugReport(
            bug_id=f"bug-{uuid.uuid4()}",
            test_id=test_case.test_id,
            failure_type=failure_type,
            file_path=test_case.file_path,
            error_message=error_output[:500],
            severity="high" if failure_type in ["syntax_error", "dependency_error"] else "medium",
        )

    def _detect_regression(self, previous_report: TestReport, new_report: TestReport) -> bool:
        """Detect regression by comparing test reports.

        Args:
            previous_report: Test report before corrections
            new_report: Test report after corrections

        Returns:
            True if regression detected (new failures introduced)
        """
        # Compare test outcomes by test name
        previous_results = {tc.test_name: tc.status for tc in previous_report.test_cases}
        new_results = {tc.test_name: tc.status for tc in new_report.test_cases}
        
        newly_failed = []
        newly_passed = []
        
        for test_name, new_status in new_results.items():
            if test_name in previous_results:
                old_status = previous_results[test_name]
                
                # Check if a previously passing test now fails
                if old_status == "passed" and new_status == "failed":
                    newly_failed.append(test_name)
                
                # Check if a previously failing test now passes
                if old_status == "failed" and new_status == "passed":
                    newly_passed.append(test_name)
        
        # Regression detected if any previously passing test now fails
        regression_detected = len(newly_failed) > 0
        
        if regression_detected:
            print(f"Regression detected: {len(newly_failed)} newly failed tests: {newly_failed}")
            print(f"Newly passed tests: {newly_passed}")
        
        return regression_detected

    def _classify_failures(self, test_report: TestReport) -> List[BugReport]:
        """Classify all test failures.

        Args:
            test_report: Test report with failures

        Returns:
            List of bug reports
        """
        return test_report.bug_reports

    def _request_corrections(self, bug_reports: List[BugReport], state: WorkflowState) -> bool:
        """Request code corrections for bugs.

        Args:
            bug_reports: List of bug reports
            state: Current workflow state

        Returns:
            True if corrections were made
        """
        if not bug_reports:
            return False

        # Convert BugReport objects to dicts if needed
        bug_report_dicts = []
        for bug in bug_reports:
            if isinstance(bug, dict):
                bug_report_dicts.append(bug)
            else:
                bug_report_dicts.append(bug.model_dump())

        # Call Construction Agent to apply corrections
        construction_agent = ConstructionAgent(llm=self.llm)

        try:
            correction_result = construction_agent.apply_corrections(
                bug_report_dicts,
                state,
            )

            # Check if any files were corrected
            corrected_files = correction_result.get("corrected_files", [])
            return len(corrected_files) > 0

        except Exception as e:
            # Log error but don't fail the entire workflow
            print(f"Correction failed: {str(e)}")
            return False

    def _rollback_corrections(self, bug_reports: List[BugReport], state: WorkflowState, reason: str):
        """Rollback corrected files to previous working versions.

        Args:
            bug_reports: List of bug reports that were corrected
            state: Current workflow state
            reason: Reason for rollback
        """
        workspace_path = state.get("workspace_path")
        if not workspace_path:
            return

        construction_agent = ConstructionAgent(llm=self.llm)

        for bug in bug_reports:
            file_path = bug.get("file_path")
            if not file_path:
                continue

            relative_path = file_path  # Already relative
            working_version = self.version_manager.get_working_version(relative_path)

            if working_version:
                # Rollback to working version
                construction_agent.rollback_file(
                    file_path=relative_path,
                    version=working_version.version,
                    reason=reason,
                )

    def _mark_corrections_as_working(self, bug_reports: List[BugReport], state: WorkflowState):
        """Mark corrected files as working versions.

        Args:
            bug_reports: List of bug reports that were corrected
            state: Current workflow state
        """
        workspace_path = state.get("workspace_path")
        if not workspace_path:
            return

        for bug in bug_reports:
            file_path = bug.get("file_path")
            if not file_path:
                continue

            relative_path = file_path  # Already relative
            latest_version = self.version_manager.get_latest_version(relative_path)

            if latest_version:
                self.version_manager.mark_as_working(relative_path, latest_version.version)
